import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const read=p=>fs.readFileSync(new URL('../'+p,import.meta.url),'utf8');
const data=JSON.parse(read('services.json'));
const backendFile=new URL('../../knownfix-release-backend/services.json',import.meta.url);
if(fs.existsSync(backendFile)) assert.deepEqual(data,JSON.parse(fs.readFileSync(backendFile,'utf8')));
const s=data.services.find(s=>s.id==='microsite-launch');
assert.equal(s.priceUsdCents,29900); assert.equal(s.deliveryBusinessDays,5); assert.equal(s.requiresScopeApproval,true);
const hub=read('services.html'), detail=read('services/microsite-launch.html'), example=read('examples/patchnote.html');
assert(detail.includes(s.scope)); assert(detail.includes(s.limitations));
assert(detail.includes('approved copy/assets and payment'));
assert(detail.includes('Patchnote example microsite'));
assert(!detail.includes('?service=microsite-launch#order'));
assert(!detail.includes('test access'));
assert(!example.includes('<script')); assert(!example.includes('<form'));
assert(example.includes('Fictional example')); assert(example.includes('Not a live product or client project'));
assert.equal((example.match(/<h1>/g)||[]).length,1);
assert(hub.includes("var launch=service&&service.id==='microsite-launch'"));
assert(hub.includes('KnownFix%20Microsite%20Launch'));
for(const [,script] of hub.matchAll(/<script>([\s\S]*?)<\/script>/g)) new vm.Script(script);
const schema=JSON.parse(hub.match(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/)[1]);
assert.equal(schema.numberOfItems,10);
assert(schema.itemListElement.find(v=>v.item.name===s.title).item.offers.url.includes('Microsite%20Launch'));
assert(schema.itemListElement.find(v=>v.item.name==='SaaS Security Exposure Review').item.offers.url.includes('SaaS%20Security'));
const row=hub.split('<tr ').find(r=>r.includes('./services/microsite-launch.html'));
assert(row.includes('data-kind="website"'));
for(const p of ['index.html','llms.txt','llms-full.txt','sitemap.xml']) assert(read(p).includes('microsite-launch'),p);
console.log('PASS Microsite Launch: approved scope/price/clock, manual gate, independent SaaS contact, fictional example and discovery.');
