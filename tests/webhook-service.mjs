import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const read = p => fs.readFileSync(new URL('../' + p, import.meta.url), 'utf8');
const data = JSON.parse(read('services.json'));
const service = data.services.find(s => s.id === 'webhook-reliability-review');
assert.equal(data.services.length, 8);
assert.equal(service.priceUsdCents, 17900);
assert.equal(service.deliveryBusinessDays, 3);
assert.equal(service.targetKind, 'github-repository');
const hub = read('services.html');
const schema = JSON.parse(hub.match(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/)[1]);
assert.equal(schema.numberOfItems, data.services.length);
assert.equal(schema.itemListElement.find(s=>s.item.name===service.title).item.offers.price,'179.00');
const embedded = JSON.parse(hub.match(/services=(\[[\s\S]*?\]),sdkUrl=/)[1]);
assert.deepEqual(embedded, data.services);
assert(hub.includes('value="' + service.id + '"'));
assert(hub.includes('data-service="' + service.id + '"'));
for (const [, script] of hub.matchAll(/<script>([\s\S]*?)<\/script>/g)) new vm.Script(script);
const detail = read('services/' + service.id + '.html');
assert(detail.includes(service.scope));
assert(detail.includes(service.limitations));
assert(detail.includes('?service=' + service.id + '#order'));
assert(detail.includes('Owner-only statistics.'));
assert(!detail.includes('The books are public.'));
assert(detail.includes('/free-skills/webhook-delivery-triage.html'));
assert(read('free-skills/webhook-delivery-triage.html').includes('../services/webhook-reliability-review.html'));
for(const p of ['index.html','sitemap.xml','llms.txt','llms-full.txt']) assert(read(p).includes(service.id));
console.log('Paid webhook service: approved price/scope, seven-service checkout/catalog/schema and discovery passed.');

